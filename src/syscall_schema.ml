(** Syscall families for filtering, corresponding to strace trace groups *)
module Family = struct
  type t =
    | All
    | Desc
    | File
    | Memory
    | Network
    | Process
    | Signal
    | Ipc
  [@@deriving sexp_of, equal, compare, enumerate]

  let to_display_string = function
    | All -> "all"
    | Desc -> "%desc"
    | File -> "%file"
    | Memory -> "%memory"
    | Network -> "%net"
    | Process -> "%process"
    | Signal -> "%signal"
    | Ipc -> "%ipc"
  ;;

  (** Returns true if the given syscall name belongs to this family. This is an
      approximation; strace uses the kernel's classification internally. *)
  let includes t ~syscall_name =
    match t with
    | All -> true
    | Desc ->
      List.mem
        ~equal:String.equal
        [ "read"
        ; "write"
        ; "open"
        ; "openat"
        ; "close"
        ; "lseek"
        ; "pread64"
        ; "pwrite64"
        ; "readv"
        ; "writev"
        ; "dup"
        ; "dup2"
        ; "dup3"
        ; "fstat"
        ; "newfstatat"
        ; "fcntl"
        ; "ioctl"
        ; "ftruncate"
        ; "fchmod"
        ; "fchown"
        ; "fchdir"
        ; "fstatfs"
        ; "getdents64"
        ; "epoll_create"
        ; "epoll_create1"
        ; "epoll_ctl"
        ; "epoll_wait"
        ; "epoll_pwait"
        ; "select"
        ; "poll"
        ; "ppoll"
        ; "pipe"
        ; "pipe2"
        ; "sendfile"
        ; "socket"
        ; "connect"
        ; "accept"
        ; "accept4"
        ; "bind"
        ; "listen"
        ; "sendto"
        ; "recvfrom"
        ; "sendmsg"
        ; "recvmsg"
        ; "shutdown"
        ; "setsockopt"
        ; "getsockopt"
        ; "getsockname"
        ; "getpeername"
        ; "socketpair"
        ; "eventfd2"
        ; "timerfd_create"
        ; "timerfd_settime"
        ; "timerfd_gettime"
        ; "signalfd4"
        ; "inotify_init1"
        ; "inotify_add_watch"
        ; "inotify_rm_watch"
        ]
        syscall_name
    | File ->
      List.mem
        ~equal:String.equal
        [ "open"
        ; "openat"
        ; "stat"
        ; "lstat"
        ; "newfstatat"
        ; "access"
        ; "faccessat"
        ; "unlink"
        ; "unlinkat"
        ; "rename"
        ; "renameat"
        ; "renameat2"
        ; "mkdir"
        ; "mkdirat"
        ; "rmdir"
        ; "link"
        ; "linkat"
        ; "symlink"
        ; "symlinkat"
        ; "readlink"
        ; "readlinkat"
        ; "chmod"
        ; "fchmod"
        ; "chown"
        ; "fchown"
        ; "truncate"
        ; "ftruncate"
        ; "getcwd"
        ; "chdir"
        ; "fchdir"
        ; "statfs"
        ; "fstatfs"
        ; "statx"
        ]
        syscall_name
    | Memory ->
      List.mem ~equal:String.equal [ "mmap"; "munmap"; "mprotect"; "brk" ] syscall_name
    | Network ->
      List.mem
        ~equal:String.equal
        [ "socket"
        ; "connect"
        ; "accept"
        ; "accept4"
        ; "bind"
        ; "listen"
        ; "sendto"
        ; "recvfrom"
        ; "sendmsg"
        ; "recvmsg"
        ; "shutdown"
        ; "setsockopt"
        ; "getsockopt"
        ; "getsockname"
        ; "getpeername"
        ; "socketpair"
        ]
        syscall_name
    | Process ->
      List.mem
        ~equal:String.equal
        [ "execve"
        ; "fork"
        ; "vfork"
        ; "clone"
        ; "clone3"
        ; "exit_group"
        ; "wait4"
        ; "waitid"
        ; "kill"
        ; "getpid"
        ; "getppid"
        ; "getuid"
        ; "getgid"
        ; "geteuid"
        ; "getegid"
        ; "prctl"
        ]
        syscall_name
    | Signal ->
      List.mem
        ~equal:String.equal
        [ "rt_sigaction"; "rt_sigprocmask"; "rt_sigreturn"; "sigaltstack"; "kill" ]
        syscall_name
    | Ipc ->
      (* IPC syscalls like shmget, semget, msgget, etc. We keep a minimal set here *)
      List.mem ~equal:String.equal [] syscall_name
  ;;
end

