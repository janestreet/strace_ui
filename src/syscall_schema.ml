    | File_descriptor -> true
    | _ -> false
  ;;
end

module Signature = struct
  type t =
    { c_signature : string
    ; args : Arg_spec.t list
    ; return_type : Return_type.t
    }
  [@@deriving sexp_of, fields ~getters]
end

module Syscall_info = struct
  type t =
    { name : string
    ; signatures : Signature.t list
    ; brief : string
    ; man_section : int
    }
  [@@deriving sexp_of, fields ~getters]

  let best_signature t ~arg_count =
    match
      List.find t.signatures ~f:(fun sig_ ->
        List.length (Signature.args sig_) = arg_count)
    with
    | Some s -> s
    | None ->
      (* Fall back to the signature with the most args (most detailed) *)
      List.max_elt t.signatures ~compare:(fun a b ->
        Int.compare (List.length (Signature.args a)) (List.length (Signature.args b)))
      |> Option.value ~default:(List.hd_exn t.signatures)
  ;;
end

